const (
	managedMarker  = "Generated by Amita Companion"
	commandTimeout = 5 * time.Second
	ManagedEnv     = "AMITA_COMPANION_MANAGED"
)

type Registration struct {
	Present   bool   `json:"present"`
	Enabled   bool   `json:"enabled"`
	Managed   bool   `json:"managed"`
	Mechanism string `json:"mechanism"`
	Location  string `json:"location,omitempty"`
	Note      string `json:"note,omitempty"`
}

func Label(state string) string {
	h := sha256.Sum256([]byte(filepath.Clean(state)))
	return "com.amita.companion." + hex.EncodeToString(h[:6])
}
func BinaryPath(state string) string { return filepath.Join(state, "bin", "amita-companion") }

func installBinary(state, binary string) error {
	dst := BinaryPath(state)
	if err := config.EnsureDir(filepath.Dir(dst)); err != nil {
		return err
	}
	source, err := os.Open(binary)
	if err != nil {
		return err
	}
	defer source.Close()
	if from, e := source.Stat(); e == nil {
		if to, e := os.Stat(dst); e == nil && os.SameFile(from, to) {
			return nil
		}
	}
	target, err := os.CreateTemp(filepath.Dir(dst), ".amita-companion-*")
	if err != nil {
		return err
	}
	defer os.Remove(target.Name())
	if err = target.Chmod(0700); err == nil {
		_, err = io.Copy(target, source)
	}
	if err == nil {
		err = target.Sync()
	}
	closeErr := target.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return os.Rename(target.Name(), dst)
}

func Enable(state, binary string) error {
	if err := installBinary(state, binary); err != nil {
		return err
	}
	return enable(state, os.Getenv("PATH"))
}
func Install(state, binary string) error { return Enable(state, binary) }
func Refresh(state string) error {
	registration, err := Inspect(state)
	if err != nil {
		return err
	}
	if !registration.Present || !registration.Managed || !registration.Enabled {
		return nil
	}
	return refresh(state, os.Getenv("PATH"))
}
func Uninstall(state string) error {
	if err := Disable(state); err != nil {
		return err
	}
	if err := os.Remove(BinaryPath(state)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

func writeManaged(path, content string) error {
	previous, err := os.ReadFile(path)
	if err == nil && !strings.Contains(string(previous), managedMarker) {
		return fmt.Errorf("autostart entry is not managed by Amita: %s", path)
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err = os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0600)
}
func readRegistration(path, mechanism string) (Registration, error) {
	registration := Registration{Location: path, Mechanism: mechanism}
	b, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return registration, nil
	}
	if err != nil {
		return registration, err
	}
	registration.Present = true
	registration.Managed = strings.Contains(string(b), managedMarker)
	registration.Enabled = true
	return registration, nil
}
func removeManaged(path string) error {
	b, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !strings.Contains(string(b), managedMarker) {
		return fmt.Errorf("autostart entry is not managed by Amita: %s", path)
	}
	return os.Remove(path)
}
func command(name string, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), commandTimeout)
	defer cancel()
	b, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	if err != nil {
		return b, fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(b)))
	}
	return b, nil
}

